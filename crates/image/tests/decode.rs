fn jpeg_decodes_as_libjpeg_9a() {
    let img = decode_jpg(JPEG_420).unwrap();
    assert_eq!((img.width, img.height), (16, 16));
    assert_eq!(
        img.rgba[..12],
        [0, 0, 23, 255, 9, 0, 56, 255, 31, 1, 71, 255]
    );
    // CRC-32 of the pixels from OpenJK's lib/jpeg-9a; libjpeg-turbo (Pillow) gives
    // 32b79d96, smoothing the chroma with its triangle filter instead.
    assert_eq!(format!("{:08x}", crc32fast::hash(&img.rgba)), "8862af3c");
}

